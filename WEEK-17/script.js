// Adding elements to an Array


// Imagine a Box of Toys!
// In JavaScript, an array is like a special box where you can keep a bunch of your favorite toys all together. Each toy has a specific spot in the box, and we can use numbers to keep track of them.


// push; This is like putting a new toy into the box at the very back. Imagine pushing it through a little door at the end. We use push() to add things to the end of an array.
// unshift; This is like carefully placing a new toy at the very front of the box. Maybe there's a special slot at the beginning. We use unshift() to add things to the beginning of an array.
// pop; This is like reaching into the box and taking out the toy at the very back. It's the one you can most easily grab! We use pop() to remove the last element from an array.
// shift; This is like carefully taking out the toy at the very front of the box. Maybe you need to move the other toys a little to get it out. We use shift() to remove the first element from an array.

const example = [];
example.unshift(90);
console.log(example);
example.unshift(102);
console.log(example);
example.unshift(-1);
console.log(example);
example.unshift("Bala Blue");
console.log(example);



// splice
// splice is used to remove or replace elements in an array
// This is like a super-handy tool that lets you take out toys from anywhere in the box, or even put new ones in specific places! It's like having a special tool to rearrange the toys inside. We use splice() to remove or replace elements within an array.


